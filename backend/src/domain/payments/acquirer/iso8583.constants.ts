export function isApprovalResponse(rc: string): boolean {
  return /^(00|08|10|11|16|8[0-9A-F]|9[0-3A-F]|Y[0-9A-F])$/.test(String(rc).toUpperCase());
}

export function isDeclineResponse(rc: string): boolean {
  return !isApprovalResponse(rc);
}

export function isReversalMti(mti: string): boolean {
  return ['0400', '0420', '0410', '0430'].includes(String(mti));
}

export function isAdviceMti(mti: string): boolean {
  return ['0120', '0130', '0220', '0230', '0420', '0430', '0520', '0530', '0620', '0630', '0820', '0830'].includes(String(mti));
}

export function isRequestMti(mti: string): boolean {
  return ['0100', '0200', '0400', '0500', '0600', '0700', '0800'].includes(String(mti));
}

export function isResponseMti(mti: string): boolean {
  return isRequestMti(String(Number(mti) + 10));
}

export function dualMessageResponseMti(requestMti: string): string {
  const map: Record<string, string> = {
    '0100': '0110', '0120': '0130',
    '0200': '0210', '0220': '0230',
    '0400': '0410', '0420': '0430',
    '0500': '0510', '0520': '0530',
    '0600': '0610', '0620': '0630',
    '0800': '0810', '0820': '0830',
  };
  return map[requestMti] || `${String(Number(requestMti) + 10).padStart(4, '0')}`;
}
