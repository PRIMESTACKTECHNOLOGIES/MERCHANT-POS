export const TEST_CARDS: readonly TestCardRecord[] = Object.freeze(rawCards);

export function findTestCardByPan(pan: string): TestCardRecord | undefined {
  const clean = String(pan || '').replace(/\D/g, '');
  return TEST_CARDS.find(c => c.pan === clean || clean.endsWith(c.pan.slice(-4)));
}

export function findTestCardById(id: string): TestCardRecord | undefined {
  return TEST_CARDS.find(c => c.id.toUpperCase() === String(id || '').toUpperCase());
}

export function listTestCardsByScheme(scheme: BrandScheme): TestCardRecord[] {
  return TEST_CARDS.filter(c => c.scheme === scheme);
}

export function listCertTestCards(): TestCardRecord[] {
  return TEST_CARDS.filter(c => c.source !== 'PRIMESTACK_INTERNAL');
}
